/*
 * Iconos de F9 como vectores propios (24dp, trazado Material). Los iconos oficiales llegan con E1.2/E1.4;
 * mientras tanto esto evita agregar la dependencia de material-icons. Reemplazables sin cambiar la UI.
 */

private fun icon(name: String, pathData: ImageVector.Builder.() -> Unit): ImageVector =
    ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f).apply(pathData).build()

